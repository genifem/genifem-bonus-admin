// Writes src/app/tokens.css from packages/shared/src/tokens.ts.
//   pnpm tokens          regenerate
//   pnpm tokens:check    fail if the committed file is stale (runs in `pnpm test`)
//
// The token source is TypeScript because React Native reads the same object and cannot read
// CSS variables. Node strips the types on import (>=22.18), so there is no build step.
//
// Colours, the type scale, the radii, the tracking scale, control densities, motion and
// shadows are emitted. Overriding Tailwind's --radius-* is the point rather than an accident:
// re-pointing the names changes every existing `rounded-*` without editing a component.
// Spacing stays in TypeScript for the Expo app, which is the only consumer that needs it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  buttonHeight,
  controlDensity,
  crewStars,
  light,
  motion,
  radius,
  shadow,
  sidebar,
  tracking,
  typeScale,
} from "../packages/shared/src/tokens.ts";

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, "../src/app/tokens.css");

// camelCase → kebab-case, with a dash before a trailing number: cream2 → cream-2,
// redAction → red-action, surfaceRaised → surface-raised.
const kebab = (name) =>
  name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/([a-z])([0-9])/g, "$1-$2");
const lines = (entries) => entries.join("\n");
const rem = (px) => `${px / 16}rem`;

const semantic = lines(
  Object.entries(light).map(([name, value]) => `  --${kebab(name)}: ${value};`),
);

// The rail's palette is its own small scale, beside the semantic one rather than inside it:
// nothing outside the navigation rail should be reaching for these.
const rail = lines(
  Object.entries(sidebar).map(([name, value]) => `  --sidebar-${kebab(name)}: ${value};`),
);

const utilities = lines(
  Object.keys(light).map((name) => `  --color-${kebab(name)}: var(--${kebab(name)});`),
);

const railUtilities = lines(
  Object.keys(sidebar).map((name) => `  --color-sidebar-${kebab(name)}: var(--sidebar-${kebab(name)});`),
);

// The Crew Stars palette by name (bg-butter, text-gold-ink, bg-red-soft). Fixed values; a
// name the semantic layer already defines (muted) is left to it.
const palette = lines(
  Object.entries(crewStars)
    .filter(([name]) => !(name in light))
    .map(([name, value]) => `  --color-${kebab(name)}: ${value};`),
);

// Steps without a line height (13px and friends) emit only the size.
const text = lines(
  Object.entries(typeScale).map(([name, { size, line }]) =>
    line
      ? `  --text-${name}: ${size};\n  --text-${name}--line-height: ${line};`
      : `  --text-${name}: ${size};`,
  ),
);

const radii = lines(Object.entries(radius).map(([n, v]) => `  --radius-${n}: ${v};`));
const trackings = lines(Object.entries(tracking).map(([n, v]) => `  --tracking-${n}: ${v};`));

// `h-control` follows the density of whatever it sits in; the named heights are fixed.
const heights = lines([
  "  --height-control: var(--control-h);",
  ...Object.entries(buttonHeight).map(([n, px]) => `  --height-control-${n}: ${rem(px)};`),
  ...Object.entries(controlDensity).map(([n, d]) => `  --height-control-${n}: ${rem(d.height)};`),
]);

const durations = lines(
  Object.entries(motion.duration).map(([n, ms]) => `  --transition-duration-${n}: ${ms}ms;`),
);
const easings = lines(
  Object.entries(motion.easing).map(([n, curve]) => `  --ease-${n}: cubic-bezier(${curve.join(", ")});`),
);
const shadows = lines(Object.entries(shadow).map(([n, v]) => `  --shadow-${n}: ${v};`));

const density = (d) =>
  [
    `  --control-h: ${rem(d.height)};`,
    `  --control-px: ${rem(d.paddingX)};`,
    `  --control-text: ${rem(d.text)};`,
    `  --control-radius: ${rem(d.radius)};`,
  ].join("\n");

const densities = Object.entries(controlDensity)
  .map(([name, d]) =>
    name === "form"
      ? `:root,\n[data-density="form"] {\n${density(d)}\n}`
      : `[data-density="${name}"] {\n${density(d)}\n}`,
  )
  .join("\n\n");

const css = `/* Generated by scripts/tokens.mjs from packages/shared/src/tokens.ts. Do not edit by hand. */

/* The semantic layer and the rail. Fixed for v1: one operator, one light look. */
:root {
${semantic}

${rail}
}

/* Control densities. A shell sets data-density once and every field and button inside it
   takes that height, padding, text size and radius. Forms are the default. */
${densities}

/* What the utilities resolve to. \`inline\` keeps the var reference, so a subtree that
   re-points a semantic variable re-skins the utilities below it. */
@theme inline {
${utilities}
${railUtilities}

${text}

${radii}

${trackings}

${heights}

${shadows}
}

@theme {
${palette}

${durations}

${easings}
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
  } catch {
    /* missing counts as stale */
  }
  if (current !== css) {
    console.error(
      "src/app/tokens.css is out of date with packages/shared/src/tokens.ts.\nRun: pnpm tokens",
    );
    process.exit(1);
  }
  console.log("tokens.css is up to date");
} else {
  writeFileSync(target, css);
  console.log(`wrote ${target}`);
}
